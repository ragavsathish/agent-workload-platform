import type {
  ActivityOverlay,
  BuildOptions,
  DiagramSource,
  EvidenceStyle,
} from "pipecat:c4-grafana/c4-grafana@0.1.0";
import type { EvidenceStatus } from "pipecat:c4-grafana/types@0.1.0";

const MAX_DIAGRAMS = 32;
const MAX_EVIDENCE_STYLES = 4_096;
const MAX_ACTIVITY_OVERLAYS = 512;
const MAX_SOURCE_BYTES = 1_048_576;
const MAX_OUTPUT_BYTES = 8_388_608;
const encoder = new TextEncoder();
const identifier = /^[A-Za-z][A-Za-z0-9_-]{0,127}$/u;
// Grafana query references are single uppercase letters. Keeping this stricter
// than Grafana's JSON schema prevents downstream panels from trapping on
// human-readable identifiers such as `voice_edge` or `EDGE`.
const queryReference = /^[A-Z]$/u;
const dashboardUid = /^[A-Za-z0-9_-]{1,128}$/u;
const colors: Record<EvidenceStatus, readonly [string, string]> = {
  strong: ["#236f4f", "#56e39f"],
  partial: ["#7c5e27", "#ffbd76"],
  observed: ["#27638e", "#72b7ef"],
  weak: ["#7d303d", "#ff778a"],
};

function bytes(value: string): number {
  return encoder.encode(value).length;
}

function requireText(value: string, name: string, maximum: number): void {
  if (typeof value !== "string" || value.trim().length === 0) {
    throw new Error(`${name} must not be empty`);
  }
  if (bytes(value) > maximum) throw new Error(`${name} exceeds ${maximum} bytes`);
}

function requireIdentifier(value: string, name: string): void {
  if (!identifier.test(value)) throw new Error(`${name} is not a safe Mermaid identifier`);
}

function escapePrometheusLabel(value: string): string {
  if (bytes(value) > 256 || /[\u0000-\u001f\u007f]/u.test(value)) {
    throw new Error("service-name is invalid");
  }
  return value.replaceAll("\\", "\\\\").replaceAll('"', '\\"');
}

function query(refId: string, serviceName: string): object {
  const expression = serviceName === "*"
    ? "sum(increase(pipecat_operation_total[$__range])) or vector(0)"
    : `sum(increase(pipecat_operation_total{service_name="${escapePrometheusLabel(serviceName)}"}[$__range])) or vector(0)`;
  return {
    datasource: { type: "prometheus", uid: "prometheus" },
    editorMode: "code",
    expr: expression,
    instant: true,
    legendFormat: refId,
    range: false,
    refId,
  };
}

function decorate(
  diagram: DiagramSource,
  evidence: readonly EvidenceStyle[],
  activity: readonly ActivityOverlay[],
): string {
  const nativeC4 = /^\s*C4(?:Context|Container|Component|Dynamic|Deployment)\b/mu.test(diagram.mermaid);
  const staticStyles = evidence.map(({ elementId, status }) => {
    const [fill, stroke] = colors[status];
    return nativeC4
      ? `UpdateElementStyle(${elementId}, "${fill}", "#ffffff", "${stroke}")`
      : `style ${elementId} fill:${fill},color:#ffffff,stroke:${stroke},stroke-width:3px`;
  });
  const liveStyles = activity.map(({ elementId, refId }) => {
    const fill = `\${__data.${refId}:color}`;
    return nativeC4
      ? `UpdateElementStyle(${elementId}, "${fill}", "#ffffff", "#56e39f")`
      : `style ${elementId} fill:${fill},color:#ffffff,stroke:#56e39f,stroke-width:4px`;
  });
  return `${diagram.mermaid.trim()}\n\n%% Evidence colors generated by pipecat:c4-grafana.\n${staticStyles.join("\n")}\n${liveStyles.join("\n")}\n`;
}

function validate(
  options: BuildOptions,
  diagrams: readonly DiagramSource[],
  evidence: readonly EvidenceStyle[],
  activity: readonly ActivityOverlay[],
): void {
  requireText(options.dashboardTitle, "dashboard-title", 256);
  if (!dashboardUid.test(options.dashboardUid)) throw new Error("dashboard-uid is invalid");
  requireText(options.description, "description", 2_048);
  requireText(options.refresh, "refresh", 32);
  requireText(options.timeFrom, "time-from", 32);
  if (bytes(options.evidenceMarkdown) > 32_768) throw new Error("evidence-markdown exceeds 32768 bytes");
  if (diagrams.length === 0 || diagrams.length > MAX_DIAGRAMS) {
    throw new Error(`diagrams must contain 1 through ${MAX_DIAGRAMS} entries`);
  }
  if (evidence.length > MAX_EVIDENCE_STYLES) {
    throw new Error(`evidence must contain at most ${MAX_EVIDENCE_STYLES} entries`);
  }
  if (activity.length > MAX_ACTIVITY_OVERLAYS) {
    throw new Error(`activity must contain at most ${MAX_ACTIVITY_OVERLAYS} entries`);
  }
  const ids = new Set<string>();
  let sourceBytes = 0;
  for (const diagram of diagrams) {
    requireIdentifier(diagram.id, "diagram id");
    if (ids.has(diagram.id)) throw new Error(`duplicate diagram id: ${diagram.id}`);
    ids.add(diagram.id);
    requireText(diagram.title, `diagram ${diagram.id} title`, 256);
    requireText(diagram.mermaid, `diagram ${diagram.id} Mermaid`, MAX_SOURCE_BYTES);
    sourceBytes += bytes(diagram.mermaid);
    if (!Number.isInteger(diagram.width) || diagram.width < 1 || diagram.width > 24) {
      throw new Error(`diagram ${diagram.id} width must be from 1 through 24`);
    }
    if (!Number.isInteger(diagram.height) || diagram.height < 6 || diagram.height > 40) {
      throw new Error(`diagram ${diagram.id} height must be from 6 through 40`);
    }
  }
  if (sourceBytes > MAX_SOURCE_BYTES) throw new Error(`combined Mermaid exceeds ${MAX_SOURCE_BYTES} bytes`);
  for (const item of evidence) {
    if (!ids.has(item.diagramId)) throw new Error(`evidence references unknown diagram: ${item.diagramId}`);
    requireIdentifier(item.elementId, "evidence element-id");
    if (!(item.status in colors)) throw new Error(`unsupported evidence status: ${item.status}`);
  }
  const references = new Set<string>();
  for (const item of activity) {
    if (!ids.has(item.diagramId)) throw new Error(`activity references unknown diagram: ${item.diagramId}`);
    requireIdentifier(item.elementId, "activity element-id");
    if (!queryReference.test(item.refId)) {
      throw new Error(`invalid activity ref-id: ${item.refId}; expected one uppercase letter from A through Z`);
    }
    const key = `${item.diagramId}:${item.refId}`;
    if (references.has(key)) throw new Error(`duplicate query reference ${item.refId} in ${item.diagramId}`);
    references.add(key);
    escapePrometheusLabel(item.serviceName);
  }
}

function compile(
  options: BuildOptions,
  diagrams: readonly DiagramSource[],
  evidence: readonly EvidenceStyle[],
  activity: readonly ActivityOverlay[],
): string {
  validate(options, diagrams, evidence, activity);
  const panels: object[] = [];
  let panelId = 1;
  let y = 0;
  let rowX = 0;
  let rowHeight = 0;
  if (options.evidenceMarkdown.trim().length > 0) {
    panels.push({
      gridPos: { h: 8, w: 24, x: 0, y },
      id: panelId++,
      options: { content: options.evidenceMarkdown, mode: "markdown" },
      title: "Source-backed code evidence",
      type: "text",
    });
    y = 8;
  }
  for (const diagram of diagrams) {
    if (rowX + diagram.width > 24) {
      y += rowHeight;
      rowX = 0;
      rowHeight = 0;
    }
    const diagramEvidence = evidence.filter((item) => item.diagramId === diagram.id);
    const diagramActivity = activity.filter((item) => item.diagramId === diagram.id);
    panels.push({
      datasource: { type: "prometheus", uid: "prometheus" },
      description: "Static evidence strength with live PromQL activity intensity for instrumented elements.",
      fieldConfig: {
        defaults: {
          color: { mode: "thresholds" },
          mappings: [],
          thresholds: {
            mode: "absolute",
            steps: [
              { color: "#1c362b", value: null },
              { color: "#1d523b", value: 1 },
              { color: "#247451", value: 10 },
              { color: "#359e6c", value: 100 },
              { color: "#56e39f", value: 1000 },
            ],
          },
        },
        overrides: [],
      },
      gridPos: { h: diagram.height, w: diagram.width, x: rowX, y },
      id: panelId++,
      options: {
        content: decorate(diagram, diagramEvidence, diagramActivity),
        escapeSpecialChars: true,
        maxDataRows: 100,
        showSeriesCount: diagramActivity.length > 0,
        seriesCountSize: "sm",
      },
      pluginVersion: "1.0.6",
      targets: diagramActivity.map((item) => query(item.refId, item.serviceName)),
      title: diagram.title,
      type: "neildengg-grafmaid-panel",
    });
    rowX += diagram.width;
    rowHeight = Math.max(rowHeight, diagram.height);
    if (rowX === 24) {
      y += rowHeight;
      rowX = 0;
      rowHeight = 0;
    }
  }
  const document = JSON.stringify({
    annotations: { list: [] },
    description: options.description,
    editable: false,
    fiscalYearStartMonth: 0,
    graphTooltip: 1,
    links: [],
    panels,
    refresh: options.refresh,
    schemaVersion: 41,
    tags: ["c4", "architecture", "evidence", "prometheus", "wassette"],
    templating: { list: [] },
    time: { from: options.timeFrom, to: "now" },
    timepicker: {},
    timezone: "browser",
    title: options.dashboardTitle,
    uid: options.dashboardUid,
    version: 1,
  }, null, 2);
  if (bytes(document) > MAX_OUTPUT_BYTES) throw new Error(`dashboard exceeds ${MAX_OUTPUT_BYTES} bytes`);
  return `${document}\n`;
}

export function compileDashboard(
  options: BuildOptions,
  diagrams: DiagramSource[],
  evidence: EvidenceStyle[],
  activity: ActivityOverlay[],
): string {
  try {
    return compile(options, diagrams, evidence, activity);
  } catch (cause) {
    // A WIT `result<string, string>` is represented by returning the success
    // value or throwing the declared string error. Throwing an Error object
    // cannot be lowered as a string and is surfaced by the host as a trap.
    throw cause instanceof Error ? cause.message : String(cause);
  }
}

