(ns c4-dashboard
  (:require [cheshire.core :as json]
            [clojure.string :as str]))

(def ^:private max-diagrams 32)
(def ^:private max-evidence-styles 4096)
(def ^:private max-activity-overlays 512)
(def ^:private max-source-bytes 1048576)
(def ^:private max-output-bytes 8388608)
(def ^:private identifier-pattern #"[A-Za-z][A-Za-z0-9_-]{0,127}")
(def ^:private query-reference-pattern #"[A-Z]")
(def ^:private dashboard-uid-pattern #"[A-Za-z0-9_-]{1,128}")
(def ^:private activity-text "#07130d")
(def ^:private neutral-fill "#3f3f46")
(def ^:private neutral-text "#f4f4f5")
(def ^:private colors
  {"strong" ["#236f4f" "#56e39f"]
   "partial" ["#7c5e27" "#ffbd76"]
   "observed" ["#27638e" "#72b7ef"]
   "weak" ["#7d303d" "#ff778a"]})

(defn- bytes [value]
  (alength (.getBytes ^String value "UTF-8")))

(defn- require-text! [value name maximum]
  (when-not (and (string? value) (not (str/blank? value)))
    (throw (ex-info (str name " must not be empty") {})))
  (when (> (bytes value) maximum)
    (throw (ex-info (str name " exceeds " maximum " bytes") {}))))

(defn- require-identifier! [value name]
  (when-not (and (string? value) (re-matches identifier-pattern value))
    (throw (ex-info (str name " is not a safe Mermaid identifier") {}))))

(defn escape-prometheus-label [value]
  (when (or (> (bytes value) 256) (re-find #"[\u0000-\u001f\u007f]" value))
    (throw (ex-info "service-name is invalid" {})))
  (-> value (str/replace "\\" "\\\\") (str/replace "\"" "\\\"")))

(defn- query [ref-id service-name]
  (let [escaped (escape-prometheus-label service-name)
        expression (cond
                     (= service-name "*")
                     "(sum(increase(pipecat_operation_total[$__range])) and on() (max(timestamp(pipecat_operation_total)) > time() - 120)) or vector(-1)"

                     (= service-name "pipecat-gitea-runner")
                     (format "(sum(gitea_runner_info{service_name=\"%s\"}) and on() (max(timestamp(gitea_runner_info{service_name=\"%s\"})) > time() - 120)) or vector(-1)" escaped escaped)

                     :else
                     (format "(sum(increase(pipecat_operation_total{service_name=\"%s\"}[$__range])) and on() (max(timestamp(pipecat_operation_total{service_name=\"%s\"})) > time() - 120)) or vector(-1)" escaped escaped))]
    {:datasource {:type "prometheus" :uid "prometheus"}
     :editorMode "code"
     :expr expression
     :instant true
     :legendFormat ref-id
     :range false
     :refId ref-id}))

(defn- decorate [diagram evidence activity]
  (let [native-c4 (boolean (re-find #"(?m)^\s*C4(Context|Container|Component|Dynamic|Deployment)\b" (:mermaid diagram)))
        evidence-by-element (into {} (map (juxt :element-id :status) evidence))
        static-styles (mapv (fn [{:keys [element-id status]}]
                              (let [stroke (second (get colors status))]
                                (if native-c4
                                  (format "UpdateElementStyle(%s, \"%s\", \"%s\", \"%s\")" element-id neutral-fill neutral-text stroke)
                                  (format "style %s fill:%s,color:%s,stroke:%s,stroke-width:3px" element-id neutral-fill neutral-text stroke))))
                            evidence)
        live-styles (mapv (fn [{:keys [element-id ref-id]}]
                            (let [activity-fill (format "${__data.%s:color}" ref-id)
                                  evidence-stroke (second (get colors (get evidence-by-element element-id "observed")))]
                              (if native-c4
                                (format "UpdateElementStyle(%s, \"%s\", \"%s\", \"%s\")" element-id activity-fill activity-text evidence-stroke)
                                (format "style %s fill:%s,color:%s,stroke:%s,stroke-width:5px" element-id activity-fill activity-text evidence-stroke))))
                          activity)]
    (str (str/trim (:mermaid diagram))
         "\n\n%% Evidence colors generated by the C4 dashboard adapter.\n"
         (str/join "\n" static-styles) "\n"
         (str/join "\n" live-styles) "\n")))

(defn- validate! [options diagrams evidence activity]
  (require-text! (:dashboard-title options) "dashboard-title" 256)
  (when-not (and (string? (:dashboard-uid options))
                 (re-matches dashboard-uid-pattern (:dashboard-uid options)))
    (throw (ex-info "dashboard-uid is invalid" {})))
  (require-text! (:description options) "description" 2048)
  (require-text! (:refresh options) "refresh" 32)
  (require-text! (:time-from options) "time-from" 32)
  (when (> (bytes (:evidence-markdown options)) 32768)
    (throw (ex-info "evidence-markdown exceeds 32768 bytes" {})))
  (when (or (empty? diagrams) (> (count diagrams) max-diagrams))
    (throw (ex-info (format "diagrams must contain 1 through %d entries" max-diagrams) {})))
  (when (> (count evidence) max-evidence-styles)
    (throw (ex-info (format "evidence must contain at most %d entries" max-evidence-styles) {})))
  (when (> (count activity) max-activity-overlays)
    (throw (ex-info (format "activity must contain at most %d entries" max-activity-overlays) {})))
  (let [ids (atom #{})
        source-bytes (atom 0)]
    (doseq [{:keys [id title mermaid width height]} diagrams]
      (require-identifier! id "diagram id")
      (when (contains? @ids id)
        (throw (ex-info (str "duplicate diagram id: " id) {})))
      (swap! ids conj id)
      (require-text! title (str "diagram " id " title") 256)
      (require-text! mermaid (str "diagram " id " Mermaid") max-source-bytes)
      (swap! source-bytes + (bytes mermaid))
      (when-not (and (integer? width) (<= 1 width 24))
        (throw (ex-info (str "diagram " id " width must be from 1 through 24") {})))
      (when-not (and (integer? height) (<= 6 height 40))
        (throw (ex-info (str "diagram " id " height must be from 6 through 40") {}))))
    (when (> @source-bytes max-source-bytes)
      (throw (ex-info (str "combined Mermaid exceeds " max-source-bytes " bytes") {})))
    (doseq [{:keys [diagram-id element-id status]} evidence]
      (when-not (contains? @ids diagram-id)
        (throw (ex-info (str "evidence references unknown diagram: " diagram-id) {})))
      (require-identifier! element-id "evidence element-id")
      (when-not (contains? colors status)
        (throw (ex-info (str "unsupported evidence status: " (name status)) {}))))
    (let [references (atom #{})]
      (doseq [{:keys [diagram-id element-id ref-id service-name]} activity]
        (when-not (contains? @ids diagram-id)
          (throw (ex-info (str "activity references unknown diagram: " diagram-id) {})))
        (require-identifier! element-id "activity element-id")
        (when-not (and (string? ref-id) (re-matches query-reference-pattern ref-id))
          (throw (ex-info (str "invalid activity ref-id: " ref-id "; expected one uppercase letter from A through Z") {})))
        (let [key [diagram-id ref-id]]
          (when (contains? @references key)
            (throw (ex-info (format "duplicate query reference %s in %s" ref-id diagram-id) {})))
          (swap! references conj key))
        (escape-prometheus-label service-name)))))

(defn compile-dashboard [{:keys [options diagrams evidence activity]}]
  (validate! options diagrams evidence activity)
  (let [has-evidence (not (str/blank? (:evidence-markdown options)))
        [panels final-y]
        (reduce (fn [[panels panel-id row-x row-y row-height] diagram]
                  (let [[x y height] (if (> (+ row-x (:width diagram)) 24)
                                       [0 (+ row-y row-height) 0]
                                       [row-x row-y row-height])
                        diagram-evidence (filterv #(= (:diagram-id %) (:id diagram)) evidence)
                        diagram-activity (filterv #(= (:diagram-id %) (:id diagram)) activity)
                        panel {:datasource {:type "prometheus" :uid "prometheus"}
                               :description (if (seq diagram-activity)
                                              "Fill shows live PromQL activity: red is missing or stale, gray is idle, and brighter cyan means more activity in the selected range. Border shows static evidence strength."
                                              "No live activity overlay is applied to this architecture detail view.")
                               :fieldConfig {:defaults {:color {:mode "thresholds"}
                                                        :mappings []
                                                        :thresholds {:mode "absolute"
                                                                     :steps [{:color "#ff778a" :value nil}
                                                                             {:color "#94a3b8" :value 0}
                                                                             {:color "#38bdf8" :value 1}
                                                                             {:color "#22d3ee" :value 10}
                                                                             {:color "#2dd4bf" :value 100}
                                                                             {:color "#56e39f" :value 1000}]}}
                                              :overrides []}
                               :gridPos {:h (:height diagram) :w (:width diagram) :x x :y y}
                               :id panel-id
                               :options {:content (decorate diagram diagram-evidence diagram-activity)
                                         :escapeSpecialChars true
                                         :maxDataRows 100
                                         :showSeriesCount (boolean (seq diagram-activity))
                                         :seriesCountSize "sm"}
                               :pluginVersion "1.0.6"
                               :links [{:title "Open Voice Product Health"
                                        :url "/metrics/d/pipecat-voice-overview/voice-product-health?${__url_time_range}"}
                                       {:title "Open Platform Resources"
                                        :url "/metrics/d/voice-system-resources/platform-resources?${__url_time_range}"}]
                               :targets (mapv #(query (:ref-id %) (:service-name %)) diagram-activity)
                               :title (:title diagram)
                               :type "neildengg-grafmaid-panel"}
                        panels (conj panels panel)
                        new-x (+ x (:width diagram))
                        new-height (max height (:height diagram))]
                    (if (= new-x 24)
                      [panels (inc panel-id) 0 (+ y new-height) 0]
                      [panels (inc panel-id) new-x y new-height])))
                [(if has-evidence
                   [{:gridPos {:h 8 :w 24 :x 0 :y 0}
                     :id 1
                     :options {:content (:evidence-markdown options) :mode "markdown"}
                     :title "Source-backed code evidence"
                     :type "text"}]
                   [])
                 (if has-evidence 2 1)
                 0
                 (if has-evidence 8 0)
                 0]
                diagrams)
        dashboard {:annotations {:list [{:builtIn 0
                                         :datasource {:type "grafana" :uid "-- Grafana --"}
                                         :enable true :hide false :iconColor "#f59e0b"
                                         :name "Deployments and E2E runs"
                                         :target {:limit 100 :matchAny true :tags ["deployment" "e2e"]}
                                         :type "dashboard"}]}
                   :description (:description options)
                   :editable false
                   :fiscalYearStartMonth 0
                   :graphTooltip 1
                   :links [{:asDropdown false :icon "dashboard" :includeVars true :keepTime true
                            :tags [] :targetBlank false :title "Voice Product Health"
                            :tooltip "RED signals and voice-flow outcomes" :type "link"
                            :url "/metrics/d/pipecat-voice-overview/voice-product-health"}
                           {:asDropdown false :icon "dashboard" :includeVars true :keepTime true
                            :tags [] :targetBlank false :title "Platform Resources"
                            :tooltip "Host, Docker, and Gondolin resource utilization" :type "link"
                            :url "/metrics/d/voice-system-resources/platform-resources"}]
                   :panels panels
                   :refresh (:refresh options)
                   :schemaVersion 41
                   :tags ["c4" "architecture" "evidence" "prometheus" "grafana-mcp"]
                   :templating {:list []}
                   :time {:from (:time-from options) :to "now"}
                   :timepicker {}
                   :timezone "browser"
                   :title (:dashboard-title options)
                   :uid (:dashboard-uid options)
                   :version 13}]
    (when (> (bytes (json/generate-string dashboard)) max-output-bytes)
      (throw (ex-info (str "dashboard exceeds " max-output-bytes " bytes") {})))
    dashboard))

(when (= *file* (System/getProperty "babashka.file"))
  (try
    (if (= "--escape-label" (first *command-line-args*))
      (println (escape-prometheus-label (second *command-line-args*)))
      (let [input (json/parse-string (slurp *in*) true)]
        (println (json/generate-string (compile-dashboard input)))))
    (catch Exception error
      (binding [*out* *err*]
        (println (.getMessage error)))
      (System/exit 1))))
