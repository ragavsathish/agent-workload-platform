const MAX_DIAGRAMS = 32;
const MAX_EVIDENCE_STYLES = 4_096;
const MAX_ACTIVITY_OVERLAYS = 512;
const MAX_SOURCE_BYTES = 1_048_576;
const MAX_OUTPUT_BYTES = 8_388_608;
const encoder = new TextEncoder();
const identifier = /^[A-Za-z][A-Za-z0-9_-]{0,127}$/u;
const queryReference = /^[A-Z]$/u;
const dashboardUid = /^[A-Za-z0-9_-]{1,128}$/u;
const activityText = "#07130d";
const neutralFill = "#3f3f46";
const neutralText = "#f4f4f5";
const colors = {
  strong: ["#236f4f", "#56e39f"],
  partial: ["#7c5e27", "#ffbd76"],
  observed: ["#27638e", "#72b7ef"],
  weak: ["#7d303d", "#ff778a"],
};

function bytes(value) {
  return encoder.encode(value).length;
}

function requireText(value, name, maximum) {
  if (typeof value !== "string" || value.trim().length === 0) {
    throw new Error(`${name} must not be empty`);
  }
  if (bytes(value) > maximum) throw new Error(`${name} exceeds ${maximum} bytes`);
}

function requireIdentifier(value, name) {
  if (!identifier.test(value)) throw new Error(`${name} is not a safe Mermaid identifier`);
}

export function escapePrometheusLabel(value) {
  if (bytes(value) > 256 || /[\u0000-\u001f\u007f]/u.test(value)) {
    throw new Error("service-name is invalid");
  }
  return value.replaceAll("\\", "\\\\").replaceAll('"', '\\"');
}

function query(refId, serviceName) {
  const escapedServiceName = escapePrometheusLabel(serviceName);
  const expression = serviceName === "*"
    ? "(sum(increase(pipecat_operation_total[$__range])) and on() (max(timestamp(pipecat_operation_total)) > time() - 120)) or vector(-1)"
    : serviceName === "pipecat-gitea-runner"
      ? `(sum(gitea_runner_info{service_name="${escapedServiceName}"}) and on() (max(timestamp(gitea_runner_info{service_name="${escapedServiceName}"})) > time() - 120)) or vector(-1)`
      : `(sum(increase(pipecat_operation_total{service_name="${escapedServiceName}"}[$__range])) and on() (max(timestamp(pipecat_operation_total{service_name="${escapedServiceName}"})) > time() - 120)) or vector(-1)`;
  return {
    datasource: { type: "prometheus", uid: "prometheus" },
    editorMode: "code",
    expr: expression,
    instant: true,
    legendFormat: refId,
    range: false,
    refId,
  };
}

function decorate(diagram, evidence, activity) {
  const nativeC4 = /^\s*C4(?:Context|Container|Component|Dynamic|Deployment)\b/mu.test(diagram.mermaid);
  const evidenceByElement = new Map(evidence.map((item) => [item["element-id"], item.status]));
  const staticStyles = evidence.map((item) => {
    const elementId = item["element-id"];
    const stroke = colors[item.status][1];
    return nativeC4
      ? `UpdateElementStyle(${elementId}, "${neutralFill}", "${neutralText}", "${stroke}")`
      : `style ${elementId} fill:${neutralFill},color:${neutralText},stroke:${stroke},stroke-width:3px`;
  });
  const liveStyles = activity.map((item) => {
    const elementId = item["element-id"];
    const refId = item["ref-id"];
    const activityFill = `\${__data.${refId}:color}`;
    const evidenceStroke = colors[evidenceByElement.get(elementId) ?? "observed"][1];
    return nativeC4
      ? `UpdateElementStyle(${elementId}, "${activityFill}", "${activityText}", "${evidenceStroke}")`
      : `style ${elementId} fill:${activityFill},color:${activityText},stroke:${evidenceStroke},stroke-width:5px`;
  });
  return `${diagram.mermaid.trim()}\n\n%% Evidence colors generated by the C4 dashboard adapter.\n${staticStyles.join("\n")}\n${liveStyles.join("\n")}\n`;
}

function validate(options, diagrams, evidence, activity) {
  requireText(options["dashboard-title"], "dashboard-title", 256);
  if (!dashboardUid.test(options["dashboard-uid"])) throw new Error("dashboard-uid is invalid");
  requireText(options.description, "description", 2_048);
  requireText(options.refresh, "refresh", 32);
  requireText(options["time-from"], "time-from", 32);
  if (bytes(options["evidence-markdown"]) > 32_768) {
    throw new Error("evidence-markdown exceeds 32768 bytes");
  }
  if (diagrams.length === 0 || diagrams.length > MAX_DIAGRAMS) {
    throw new Error(`diagrams must contain 1 through ${MAX_DIAGRAMS} entries`);
  }
  if (evidence.length > MAX_EVIDENCE_STYLES) {
    throw new Error(`evidence must contain at most ${MAX_EVIDENCE_STYLES} entries`);
  }
  if (activity.length > MAX_ACTIVITY_OVERLAYS) {
    throw new Error(`activity must contain at most ${MAX_ACTIVITY_OVERLAYS} entries`);
  }
  const ids = new Set();
  let sourceBytes = 0;
  for (const diagram of diagrams) {
    requireIdentifier(diagram.id, "diagram id");
    if (ids.has(diagram.id)) throw new Error(`duplicate diagram id: ${diagram.id}`);
    ids.add(diagram.id);
    requireText(diagram.title, `diagram ${diagram.id} title`, 256);
    requireText(diagram.mermaid, `diagram ${diagram.id} Mermaid`, MAX_SOURCE_BYTES);
    sourceBytes += bytes(diagram.mermaid);
    if (!Number.isInteger(diagram.width) || diagram.width < 1 || diagram.width > 24) {
      throw new Error(`diagram ${diagram.id} width must be from 1 through 24`);
    }
    if (!Number.isInteger(diagram.height) || diagram.height < 6 || diagram.height > 40) {
      throw new Error(`diagram ${diagram.id} height must be from 6 through 40`);
    }
  }
  if (sourceBytes > MAX_SOURCE_BYTES) throw new Error(`combined Mermaid exceeds ${MAX_SOURCE_BYTES} bytes`);
  for (const item of evidence) {
    if (!ids.has(item["diagram-id"])) throw new Error(`evidence references unknown diagram: ${item["diagram-id"]}`);
    requireIdentifier(item["element-id"], "evidence element-id");
    if (!(item.status in colors)) throw new Error(`unsupported evidence status: ${item.status}`);
  }
  const references = new Set();
  for (const item of activity) {
    if (!ids.has(item["diagram-id"])) throw new Error(`activity references unknown diagram: ${item["diagram-id"]}`);
    requireIdentifier(item["element-id"], "activity element-id");
    if (!queryReference.test(item["ref-id"])) {
      throw new Error(`invalid activity ref-id: ${item["ref-id"]}; expected one uppercase letter from A through Z`);
    }
    const key = `${item["diagram-id"]}:${item["ref-id"]}`;
    if (references.has(key)) throw new Error(`duplicate query reference ${item["ref-id"]} in ${item["diagram-id"]}`);
    references.add(key);
    escapePrometheusLabel(item["service-name"]);
  }
}

export function compileDashboard({ options, diagrams, evidence, activity }) {
  validate(options, diagrams, evidence, activity);
  const panels = [];
  let panelId = 1;
  let y = 0;
  let rowX = 0;
  let rowHeight = 0;
  if (options["evidence-markdown"].trim().length > 0) {
    panels.push({
      gridPos: { h: 8, w: 24, x: 0, y },
      id: panelId++,
      options: { content: options["evidence-markdown"], mode: "markdown" },
      title: "Source-backed code evidence",
      type: "text",
    });
    y = 8;
  }
  for (const diagram of diagrams) {
    if (rowX + diagram.width > 24) {
      y += rowHeight;
      rowX = 0;
      rowHeight = 0;
    }
    const diagramEvidence = evidence.filter((item) => item["diagram-id"] === diagram.id);
    const diagramActivity = activity.filter((item) => item["diagram-id"] === diagram.id);
    panels.push({
      datasource: { type: "prometheus", uid: "prometheus" },
      description: diagramActivity.length > 0
        ? "Fill shows live PromQL activity: red is missing or stale, gray is idle, and brighter cyan means more activity in the selected range. Border shows static evidence strength."
        : "No live activity overlay is applied to this architecture detail view.",
      fieldConfig: {
        defaults: {
          color: { mode: "thresholds" },
          mappings: [],
          thresholds: {
            mode: "absolute",
            steps: [
              { color: "#ff778a", value: null },
              { color: "#94a3b8", value: 0 },
              { color: "#38bdf8", value: 1 },
              { color: "#22d3ee", value: 10 },
              { color: "#2dd4bf", value: 100 },
              { color: "#56e39f", value: 1000 },
            ],
          },
        },
        overrides: [],
      },
      gridPos: { h: diagram.height, w: diagram.width, x: rowX, y },
      id: panelId++,
      options: {
        content: decorate(diagram, diagramEvidence, diagramActivity),
        escapeSpecialChars: true,
        maxDataRows: 100,
        showSeriesCount: diagramActivity.length > 0,
        seriesCountSize: "sm",
      },
      pluginVersion: "1.0.6",
      links: [
        {
          title: "Open Voice Product Health",
          url: "/metrics/d/pipecat-voice-overview/voice-product-health?${__url_time_range}",
        },
        {
          title: "Open Platform Resources",
          url: "/metrics/d/voice-system-resources/platform-resources?${__url_time_range}",
        },
      ],
      targets: diagramActivity.map((item) => query(item["ref-id"], item["service-name"])),
      title: diagram.title,
      type: "neildengg-grafmaid-panel",
    });
    rowX += diagram.width;
    rowHeight = Math.max(rowHeight, diagram.height);
    if (rowX === 24) {
      y += rowHeight;
      rowX = 0;
      rowHeight = 0;
    }
  }
  const dashboard = {
    annotations: {
      list: [{
        builtIn: 0,
        datasource: { type: "grafana", uid: "-- Grafana --" },
        enable: true,
        hide: false,
        iconColor: "#f59e0b",
        name: "Deployments and E2E runs",
        target: { limit: 100, matchAny: true, tags: ["deployment", "e2e"] },
        type: "dashboard",
      }],
    },
    description: options.description,
    editable: false,
    fiscalYearStartMonth: 0,
    graphTooltip: 1,
    links: [
      {
        asDropdown: false,
        icon: "dashboard",
        includeVars: true,
        keepTime: true,
        tags: [],
        targetBlank: false,
        title: "Voice Product Health",
        tooltip: "RED signals and voice-flow outcomes",
        type: "link",
        url: "/metrics/d/pipecat-voice-overview/voice-product-health",
      },
      {
        asDropdown: false,
        icon: "dashboard",
        includeVars: true,
        keepTime: true,
        tags: [],
        targetBlank: false,
        title: "Platform Resources",
        tooltip: "Host, Docker, and Gondolin resource utilization",
        type: "link",
        url: "/metrics/d/voice-system-resources/platform-resources",
      },
    ],
    panels,
    refresh: options.refresh,
    schemaVersion: 41,
    tags: ["c4", "architecture", "evidence", "prometheus", "grafana-mcp"],
    templating: { list: [] },
    time: { from: options["time-from"], to: "now" },
    timepicker: {},
    timezone: "browser",
    title: options["dashboard-title"],
    uid: options["dashboard-uid"],
    version: 13,
  };
  if (bytes(JSON.stringify(dashboard)) > MAX_OUTPUT_BYTES) {
    throw new Error(`dashboard exceeds ${MAX_OUTPUT_BYTES} bytes`);
  }
  return dashboard;
}
