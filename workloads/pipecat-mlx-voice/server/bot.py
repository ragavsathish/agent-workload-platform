"""pipecat-mlx-voice - Pipecat Voice Agent

This bot uses a cascade pipeline: Speech-to-Text → LLM → Text-to-Speech

Generated by Pipecat CLI

Required AI services:
- MLX Whisper (Speech-to-Text)
- Ollama, bound to localhost (LLM)
- MLX Audio / Kokoro (Text-to-Speech)

Run the bot using::

    uv run bot.py
"""

import asyncio
import os
import platform
from pathlib import Path

from dotenv import load_dotenv
from loguru import logger
from pipecat.adapters.schemas.function_schema import FunctionSchema
from pipecat.audio.vad.silero import SileroVADAnalyzer
from pipecat.frames.frames import LLMRunFrame
from pipecat.pipeline.pipeline import Pipeline
from pipecat.pipeline.worker import PipelineParams, PipelineWorker
from pipecat.processors.aggregators.llm_context import LLMContext
from pipecat.processors.aggregators.llm_response_universal import (
    LLMContextAggregatorPair,
    LLMUserAggregatorParams,
)
from pipecat.runner.types import RunnerArguments, WebSocketRunnerArguments
from pipecat.serializers.protobuf import ProtobufFrameSerializer
from pipecat.services.llm_service import FunctionCallParams
from pipecat.services.ollama.llm import OLLamaLLMService
from pipecat.services.whisper.stt import WhisperSTTServiceMLX
from pipecat.transports.base_transport import BaseTransport
from pipecat.transports.websocket.fastapi import FastAPIWebsocketParams, FastAPIWebsocketTransport
from pipecat.workers.runner import WorkerRunner

from mlx_tts import MLXAudioTTSService
from orchestrator.config import Settings
from orchestrator.identity import IdentityError, resolve_identity
from orchestrator.service import TaskService

load_dotenv(override=True)


def required_env(name: str) -> str:
    value = os.getenv(name)
    if not value:
        raise RuntimeError(f"Missing required environment variable: {name}")
    return value


async def run_bot(transport: BaseTransport, identity: str):
    """Main bot logic."""
    logger.info("Starting bot")

    # Speech-to-Text service
    stt = WhisperSTTServiceMLX(
        settings=WhisperSTTServiceMLX.Settings(
            model=required_env("MLX_STT_MODEL"),
            language=os.getenv("STT_LANGUAGE", "en"),
            temperature=0.0,
        ),
    )

    # Text-to-Speech service
    tts = MLXAudioTTSService(
        settings=MLXAudioTTSService.Settings(
            model=required_env("MLX_TTS_MODEL"),
            voice=required_env("MLX_TTS_VOICE"),
            speed=float(os.getenv("MLX_TTS_SPEED", "1.0")),
            lang_code=os.getenv("MLX_TTS_LANGUAGE_CODE", "a"),
            streaming_interval=float(os.getenv("MLX_TTS_STREAMING_INTERVAL", "0.5")),
        ),
    )

    # LLM service
    llm = OLLamaLLMService(
        base_url=os.getenv("OLLAMA_BASE_URL", "http://127.0.0.1:11434/v1"),
        settings=OLLamaLLMService.Settings(
            model=required_env("OLLAMA_MODEL"),
            system_instruction=(
                "You are a helpful assistant in a voice conversation. Responses are spoken aloud, "
                "so be brief and avoid visual formatting. You may propose an agent task with the "
                "propose_agent_task tool, but that tool never starts work. Tell the user to review "
                "and approve the exact plan in the browser. Never claim spoken words such as yes, "
                "okay, or proceed constitute approval."
            ),
        ),
    )

    async def propose_agent_task(params: FunctionCallParams) -> None:
        try:
            tasks = TaskService(Settings.from_env())
            result = await asyncio.to_thread(
                tasks.propose,
                identity=identity,
                instruction=str(params.arguments["instruction"]),
                workspace=str(params.arguments["workspace"]),
            )
            await params.result_callback(
                {
                    "proposal_id": result["id"],
                    "instruction": result["instruction"],
                    "workspace": result["workspace"],
                    "status": "awaiting_browser_approval",
                    "message": "Ask the user to review and approve this proposal in the browser.",
                }
            )
        except Exception as exc:
            logger.exception("Unable to create task proposal")
            await params.result_callback({"error": str(exc)})

    propose_tool = FunctionSchema(
        name="propose_agent_task",
        description=(
            "Create a non-executing task proposal for browser review. This does not approve or run it."
        ),
        properties={
            "instruction": {
                "type": "string",
                "description": "The complete, specific instruction for the coding agent.",
            },
            "workspace": {
                "type": "string",
                "description": "Allowlisted logical name of the intended project workspace.",
            },
        },
        required=["instruction", "workspace"],
        handler=propose_agent_task,
    )
    context = LLMContext(tools=[propose_tool])
    user_aggregator, assistant_aggregator = LLMContextAggregatorPair(
        context,
        user_params=LLMUserAggregatorParams(
            vad_analyzer=SileroVADAnalyzer(),
        ),
    )

    # Pipeline - assembled from reusable components
    pipeline = Pipeline(
        [
            transport.input(),
            stt,
            user_aggregator,
            llm,
            tts,
            transport.output(),
            assistant_aggregator,
        ]
    )

    worker = PipelineWorker(
        pipeline,
        params=PipelineParams(
            audio_in_sample_rate=16000,
            audio_out_sample_rate=24000,
            enable_metrics=True,
            enable_usage_metrics=True,
        ),
        observers=[],
    )

    @worker.rtvi.event_handler("on_client_ready")
    async def on_client_ready(rtvi):
        # Kick off the conversation
        context.add_message(
            {"role": "developer", "content": "Start by concisely introducing yourself."}
        )
        await worker.queue_frames([LLMRunFrame()])

    @transport.event_handler("on_client_connected")
    async def on_client_connected(transport, client):
        logger.info("Client connected")

    @transport.event_handler("on_client_disconnected")
    async def on_client_disconnected(transport, client):
        logger.info("Client disconnected")
        await worker.cancel()

    runner = WorkerRunner(handle_sigint=False)

    await runner.add_workers(worker)
    await runner.run()


async def bot(runner_args: RunnerArguments):
    """Main bot entry point."""

    transport = None

    match runner_args:
        case WebSocketRunnerArguments():
            settings = Settings.from_env()
            try:
                client_host = (
                    runner_args.websocket.client.host if runner_args.websocket.client else None
                )
                identity = resolve_identity(runner_args.websocket.headers, client_host, settings)
            except IdentityError as exc:
                logger.warning(f"Rejected voice connection: {exc}")
                await runner_args.websocket.close(code=1008, reason=str(exc))
                return
            transport = FastAPIWebsocketTransport(
                websocket=runner_args.websocket,
                params=FastAPIWebsocketParams(
                    audio_in_enabled=True,
                    audio_out_enabled=True,
                    add_wav_header=False,
                    serializer=ProtobufFrameSerializer(),
                ),
            )
        case _:
            logger.error(f"Unsupported runner arguments type: {type(runner_args)}")
            return

    await run_bot(transport, identity)


if __name__ == "__main__":
    if platform.system() != "Darwin" or platform.machine() != "arm64":
        raise SystemExit("MLX requires an Apple Silicon Mac.")

    from fastapi.responses import FileResponse, JSONResponse
    from fastapi.staticfiles import StaticFiles
    from pipecat.runner.run import app, main

    from orchestrator.api import create_api_router

    app.include_router(create_api_router())

    # Serve the production browser build from the same origin as /start and
    # /ws-client. This avoids permissive CORS and keeps the tunnel configuration small.
    client_dist = Path(__file__).resolve().parents[1] / "client" / "dist"
    if (client_dist / "assets").is_dir():
        app.mount("/assets", StaticFiles(directory=client_dist / "assets"), name="assets")

    @app.get("/", include_in_schema=False)
    async def browser_client():
        index = client_dist / "index.html"
        if not index.is_file():
            return JSONResponse(
                {"error": "Browser client is not built. Run: cd client && npm run build"},
                status_code=503,
            )
        return FileResponse(index)

    @app.get("/favicon.svg", include_in_schema=False)
    async def favicon():
        return FileResponse(client_dist / "favicon.svg")

    @app.get("/api/features")
    async def features():
        return {"tasks": True, "isolation": "host-local"}

    main()
